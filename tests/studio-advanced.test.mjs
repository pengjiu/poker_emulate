test('an inspector section opened during a pending seek stays open after its refresh', async t => {
  let server, browser, releaseSeek;
  t.after(async () => { releaseSeek?.(); await browser?.close(); await server?.close(); });
  const store = await createProject(join(await temp(t), 'project'), newProject({scenes: [priceLesson()]}, {locale: 'zh-CN'}));
  server = await serve(store.directory, {port: 0}); browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
  await page.goto(server.url); await page.waitForSelector('[data-frame="range"]');
  let sought;
  const request = new Promise(resolve => { sought = resolve; }), response = new Promise(resolve => { releaseSeek = resolve; });
  await page.route('**/api/rpc', async route => {
    if (route.request().postDataJSON().method === 'seek') { sought(); await response; }
    await route.continue();
  });
  await page.locator('[data-frame="range"]').click(); await request;
  await page.locator('.advanced-tools > summary').click();
  assert.equal(await page.locator('.advanced-tools').evaluate(node => node.open), true);
  releaseSeek();
  await page.waitForSelector('[data-frame="range"].active');
  assert.equal(await page.locator('.advanced-tools').evaluate(node => node.open), true, 'the async seek must not undo an explicit expansion');
  assert.equal(await page.locator('[data-ui="advanced-artwork"]').isVisible(), true);
  await page.locator('.advanced-tools > summary').click();
  const firstFrame = await page.locator('.beat-chip').first().getAttribute('data-frame');
  await page.locator('.beat-chip').first().click();
  await page.waitForFunction(id => document.querySelector('.beat-chip.active')?.dataset.frame === id, firstFrame);
  assert.equal(await page.locator('.advanced-tools').evaluate(node => node.open), false, 'an explicit collapse is preserved too');
});

