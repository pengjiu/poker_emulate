test('course form edits ordered members and concept references through the real director', async t => {
  let server, browser;
  t.after(async () => { await browser?.close(); await server?.close(); });
  const input = fullCourseInputs(), original = structuredClone(input.lesson.course);
  const store = await createProject(join(await temp(t), 'project'), newProject(input.lesson, {locale: 'zh-CN'}));
  server = await serve(store.directory, {port: 0}); browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.url); await page.waitForSelector('#scene-select');
  const modal = page.locator('.modal-overlay');
  async function openCourse() {
    if (!await page.locator('.advanced-tools').evaluate(node => node.open)) await page.locator('.advanced-tools > summary').click();
    await page.locator('[data-ui="advanced-course"]').click();
  }
  async function save(revision) {
    await modal.locator('[data-save]').click();
    await page.waitForFunction(revision => document.querySelector('.stage-top')?.textContent.includes('r' + revision), revision);
    assert.equal(await modal.count(), 0);
    return (await store.read()).lesson.course;
  }
  const memberValues = row => row.locator('[data-member] [data-field="member"]').evaluateAll(nodes => nodes.map(node => node.value));
  const members = original.episodes[2].sceneIds, outside = input.lesson.scenes.filter(scene => !members.includes(scene.id)).slice(0, 2).map(scene => scene.id);
  await openCourse();
  let episode = modal.locator('[data-episode="2"]');
  // Previously this updated sceneId alone and the real apply failed COURSE_SCENES.
  await episode.locator('[data-field="scene"]').selectOption(outside[0]);
  assert.deepEqual(await memberValues(episode), [...members, outside[0]]);
  assert.match(await modal.locator('[data-course-notice]').textContent(), /追加/);
  await episode.locator('[data-move-member="2"][data-delta="-1"]').click();
  await episode.locator('[data-member="0"] [data-field="member"]').selectOption(outside[1]);
  await episode.locator('[data-field="sceneToAdd"]').selectOption(members[0]);
  await episode.locator('[data-add-member]').click();
  await episode.locator('[data-remove-member="2"]').click();
  assert.deepEqual(await memberValues(episode), [outside[1], outside[0], members[0]]);
  await episode.locator('[data-move-episode][data-delta="-1"]').click();
  let course = await save(1), changed = course.episodes.find(item => item.id === 'episode-3');
  assert.deepEqual(course.episodes.map(item => item.id), ['episode-1', 'episode-3', 'episode-2']);
  assert.equal(changed.sceneId, outside[0]); assert.deepEqual(changed.sceneIds, [outside[1], outside[0], members[0]]);
  assert.deepEqual(changed.objective, original.episodes[2].objective); assert.deepEqual(changed.requires, original.episodes[2].requires);
  assert.deepEqual(course.terminology, original.terminology); assert.deepEqual(course.concepts, original.concepts);

  await openCourse(); episode = modal.locator('[data-episode="1"]');
  await episode.locator('[data-remove-member="1"]').click();
  assert.equal(await episode.locator('[data-field="scene"]').inputValue(), outside[1]);
  assert.match(await modal.locator('[data-course-notice]').textContent(), /第一项/);
  await episode.locator('[data-field="scene"]').selectOption(members[0]);
  assert.deepEqual(await memberValues(episode), [outside[1], members[0]], 'choosing an existing entry does not reorder members');
  await episode.locator('[data-member="1"] [data-field="member"]').selectOption(members[1]);
  assert.equal(await episode.locator('[data-field="scene"]').inputValue(), outside[1]);
  assert.deepEqual(await memberValues(episode), [outside[1], members[1]], 'replacing the entry does not append its removed scene again');
  await episode.locator('[data-member="1"] [data-field="member"]').selectOption(members[0]);
  await episode.locator('[data-field="scene"]').selectOption(members[0]);
  course = await save(2); changed = course.episodes.find(item => item.id === 'episode-3');
  assert.equal(changed.sceneId, members[0]); assert.deepEqual(changed.sceneIds, [outside[1], members[0]]);

  await openCourse();
  const price = modal.locator('[data-concept-id="price"]');
  await price.locator('[data-field="conceptId"]').fill('price-reviewed');
  await price.locator('[data-concept-locale="zh-CN"] [data-field="description"]').fill('分别计算价格门槛和范围权益');
  await price.locator('[data-concept-locale="zh-CN"] [data-field="conditions"]').fill('仅在适用的规则与范围下比较');
  await price.locator('[data-concept-translations] > summary').click();
  await price.locator('[data-concept-locale="en-US"] [data-field="description"]').fill('Compare the price threshold with range equity.');
  await modal.locator('[data-update-concepts]').click();
  assert.equal(await modal.locator('[data-relation][value="price"]').count(), 0);
  assert.equal(await modal.locator('[data-relation][value="price-reviewed"]:checked').count(), 4);
  // Invalid renames stay in the local form, with an explicit message and no partial write.
  await modal.locator('[data-concept-id="evidence"] [data-field="conceptId"]').fill('price-reviewed');
  await modal.locator('[data-update-concepts]').click();
  assert.match(await modal.locator('[data-course-notice]').textContent(), /重复/);
  assert.equal((await store.read()).revision, 2);
  await modal.locator('[data-concept-id="evidence"] [data-field="conceptId"]').fill('evidence');
  await modal.locator('[data-update-concepts]').click();
  await modal.locator('[data-add-concept]').click();
  const added = modal.locator('[data-concept="3"]');
  await added.locator('[data-field="conceptId"]').fill('adaptation');
  await added.locator('[data-concept-locale="zh-CN"] [data-field="description"]').fill('根据新事实调整范围');
  await added.locator('[data-concept-locale="zh-CN"] [data-field="conditions"]').fill('前史可核对，样本范围明确');
  await modal.locator('[data-update-concepts]').click();
  await modal.locator('[data-episode="1"] [data-relation="introduces"][value="adaptation"]').check();
  await modal.locator('[data-episode="1"] [data-relation="recaps"][value="price-reviewed"]').check();
  await modal.locator('[data-episode="2"] [data-relation="requires"][value="price-reviewed"]').uncheck();
  await modal.locator('[data-episode="2"] [data-relation="requires"][value="adaptation"]').check();
  await modal.locator('[data-episode="2"] [data-relation="recaps"][value="price-reviewed"]').uncheck();
  await modal.locator('[data-episode="2"] [data-relation="recaps"][value="transfer"]').check();
  course = await save(3);
  const renamed = course.concepts.find(item => item.id === 'price-reviewed'), originalPrice = original.concepts.find(item => item.id === 'price');
  assert.equal(renamed.description['zh-CN'], '分别计算价格门槛和范围权益');
  assert.equal(renamed.description['en-US'], 'Compare the price threshold with range equity.');
  assert.equal(renamed.description['ja-JP'], originalPrice.description['ja-JP']);
  assert.equal(renamed.conditions['en-US'], originalPrice.conditions['en-US']);
  assert.deepEqual(course.episodes.find(item => item.id === 'episode-2').requires, ['adaptation']);
  assert.deepEqual(course.episodes.find(item => item.id === 'episode-2').recaps, ['transfer']);
  assert.deepEqual(course.episodes.find(item => item.id === 'episode-3').introduces, ['transfer', 'adaptation']);
  assert.ok(course.episodes.every(item => ['requires', 'introduces', 'recaps'].every(key => !item[key]?.includes('price'))));
  assert.deepEqual(course.terminology, original.terminology);
  assert.deepEqual(course.style, original.style);
  assert.deepEqual((await store.read()).lesson.session, input.lesson.session);
  assert.deepEqual((await store.read()).lesson.practice, input.lesson.practice);

  await openCourse();
  await modal.locator('[data-concept-id="price-reviewed"] [data-remove-concept]').click();
  assert.match(await modal.locator('[data-course-notice]').textContent(), /episode-1.*episode-3/);
  assert.equal(await modal.locator('[data-concept-id="price-reviewed"]').count(), 1);
  assert.equal((await store.read()).revision, 3);
  for (const box of await modal.locator('[data-relation][value="price-reviewed"]').all()) if (await box.isChecked()) await box.uncheck();
  await modal.locator('[data-concept-id="price-reviewed"] [data-remove-concept]').click();
  assert.equal(await modal.locator('[data-relation][value="price-reviewed"]').count(), 0);
  await modal.locator('[data-remove-episode="2"]').click();
  await modal.locator('[data-move-episode="1"][data-delta="-1"]').click();
  course = await save(4);
  assert.deepEqual(course.episodes.map(item => item.id), ['episode-3', 'episode-1']);
  const declared = new Set(course.concepts.map(item => item.id));
  assert.ok(!declared.has('price-reviewed'));
  for (const item of course.episodes) for (const key of ['requires', 'introduces', 'recaps']) assert.ok((item[key] ?? []).every(name => declared.has(name)));
  assert.deepEqual(course.episodes[0].introduces, ['transfer', 'adaptation']);
  assert.deepEqual(errors, []);
});
